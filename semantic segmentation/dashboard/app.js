function setGeoBasemap(kind) {
  if (!geoMap || !osmLayer || !satelliteLayer) return;
  const osmBtn = $('#mapOsmBtn');
  const satBtn = $('#mapSatelliteBtn');
  const status = $('#mapLayerStatus');

  if (kind === 'satellite') {
    if (geoMap.hasLayer(osmLayer)) geoMap.removeLayer(osmLayer);
    if (!geoMap.hasLayer(satelliteLayer)) satelliteLayer.addTo(geoMap);
    osmBtn?.classList.remove('active');
    satBtn?.classList.add('active');
    if (status) status.textContent = 'Satellite imagery · Esri World Imagery';
  } else {
    if (geoMap.hasLayer(satelliteLayer)) geoMap.removeLayer(satelliteLayer);
    if (!geoMap.hasLayer(osmLayer)) osmLayer.addTo(geoMap);
    satBtn?.classList.remove('active');
    osmBtn?.classList.add('active');
    if (status) status.textContent = 'Street map · OpenStreetMap';
  }
  setTimeout(() => geoMap && geoMap.invalidateSize(true), 50);
}

