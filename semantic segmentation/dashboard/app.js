async function openVisualOdometry() {
  const buttons = [$('#openVO'), $('#openVOSecondary')].filter(Boolean);
  buttons.forEach(b => {
    b.disabled = true;
    b.dataset.old = b.innerHTML;
    b.textContent = 'Opening Visual Odometry…';
  });
  try {
    const result = await api('/api/vo/launch', {});
    toast(result.already_running ? 'Visual Odometry is already running' : (result.message || 'Visual Odometry opened in a separate window'));
  } catch (e) {
    toast(e.message);
  } finally {
    buttons.forEach(b => {
      b.disabled = false;
      if (b.dataset.old) b.innerHTML = b.dataset.old;
    });
  }
}

