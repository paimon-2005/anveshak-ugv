function drawLocalVoMap(s) {
  initLocalVoMap();
  if (!localVoMap) return;

  localVoOverlayLayers.forEach(layer => localVoMap.removeLayer(layer));
  localVoOverlayLayers = [];

  const b = s.map_selection;
  if (!b) {
    if (localVoLastBoundsKey !== 'world') {
      localVoMap.setView([20, 0], 3);
      localVoLastBoundsKey = 'world';
    }
    return;
  }

  const bounds = [[b.south, b.west], [b.north, b.east]];
  const boundsKey = [b.south, b.west, b.north, b.east].map(v => Number(v).toFixed(7)).join(',');
  // Only fit to the selected area when the geographic selection changes.
  // Re-fitting on every telemetry/VO frame would constantly reset the user's zoom.
  if (localVoLastBoundsKey !== boundsKey) {
    localVoMap.fitBounds(bounds, { padding: [16, 16], maxZoom: 19, animate: false });
    localVoLastBoundsKey = boundsKey;
  }

  const voTrail = Array.isArray(s.vo_trail) ? s.vo_trail : [];
  if (voTrail.length > 1) {
    const pts = voTrail.map(p => voToLatLng(Number(p[0]), -Number(p[2]), b, b.heading_deg));
    localVoOverlayLayers.push(L.polyline(pts, {
      color:'#00e5ff',
      weight:7,
      opacity:1,
      pane:'localVoTrajectory',
      lineJoin:'round',
      lineCap:'round',
    }).bindTooltip('VISUAL ODOMETRY TRAJECTORY'));

    localVoOverlayLayers.push(L.circleMarker(pts[0], {
      radius:7, color:'#fff', fillColor:'#00e5ff', fillOpacity:1,
      weight:2, pane:'localMissionMarkers'
    }).bindTooltip('VO START'));

    localVoOverlayLayers.push(L.circleMarker(pts[pts.length - 1], {
      radius:9, color:'#fff', fillColor:'#22c55e', fillOpacity:1,
      weight:3, pane:'localMissionMarkers'
    }).bindTooltip('VO CURRENT'));
  }

  const trail = Array.isArray(s.trail) ? s.trail : [];
  if (trail.length > 1) {
    const pts = trail.map(p => localToLatLng(Number(p[0]), Number(p[1]), b, b.heading_deg));
    localVoOverlayLayers.push(L.polyline(pts, {
      color:'#22c55e', weight:3, opacity:.9, dashArray:'6 6',
      pane:'localMissionOverlay', lineJoin:'round', lineCap:'round'
    }));
  }

  const route = Array.isArray(s.route) ? s.route : [];
  if (route.length > 1) {
    const pts = route.map(p => localToLatLng(Number(p[0]), Number(p[1]), b, b.heading_deg));
    localVoOverlayLayers.push(L.polyline(pts, {
      color:'#ff2fb3', weight:4, opacity:.95, dashArray:'9 7',
      pane:'localMissionOverlay', lineJoin:'round', lineCap:'round'
    }));
  }

  if (s.pose_x != null && Number.isFinite(Number(s.pose_x))) {
    const p = localToLatLng(Number(s.pose_x), Number(s.pose_y || 0), b, b.heading_deg);
    localVoOverlayLayers.push(L.circleMarker(p, {
      radius:10, color:'#fff', fillColor:'#22c55e', fillOpacity:1,
      weight:3, pane:'localMissionMarkers'
    }).bindTooltip('ROVER · live'));
  }

  localVoOverlayLayers.forEach(layer => layer.addTo(localVoMap));
  setTimeout(() => localVoMap && localVoMap.invalidateSize(true), 30);
}

function initGeoMap() {
  initLocalVoMap();
  if (geoMap || !window.L) return;

  geoMap = L.map('geographicMap', {
    zoomControl: true,
    preferCanvas: true,
    attributionControl: true,
    zoomAnimation: true,
  }).setView([20, 0], 3);

  // Explicit panes keep basemaps below the mission overlays.
  geoMap.createPane('baseImagery');
  geoMap.getPane('baseImagery').style.zIndex = 150;
  geoMap.createPane('baseStreets');
  geoMap.getPane('baseStreets').style.zIndex = 160;
  geoMap.createPane('geoSelection');
  geoMap.getPane('geoSelection').style.zIndex = 430;
  geoMap.createPane('voTrajectory');
  geoMap.getPane('voTrajectory').style.zIndex = 700;
  geoMap.createPane('missionOverlay');
  geoMap.getPane('missionOverlay').style.zIndex = 720;
  geoMap.createPane('missionMarkers');
  geoMap.getPane('missionMarkers').style.zIndex = 740;

  // OSM street layer.
  osmLayer = L.tileLayer('https://tile.openstreetmap.org/{z}/{x}/{y}.png', {
    maxZoom: 19,
    maxNativeZoom: 19,
    keepBuffer: 2,
    updateWhenIdle: true,
    attribution: '&copy; OpenStreetMap contributors',
    pane: 'baseStreets',
  });

  // Esri World Imagery is a real satellite basemap service.
  satelliteLayer = L.tileLayer(
    'https://services.arcgisonline.com/ArcGIS/rest/services/World_Imagery/MapServer/tile/{z}/{y}/{x}',
    {
      maxZoom: 20,
      maxNativeZoom: 19,
      keepBuffer: 2,
      updateWhenIdle: true,
      crossOrigin: true,
      attribution: 'Tiles &copy; Esri — Source: Esri, Maxar, Earthstar Geographics, and the GIS User Community',
      pane: 'baseImagery',
    }
  );

  satelliteLayer.on('tileerror', () => {
    const status = $('#mapLayerStatus');
    if (status) status.textContent = 'Satellite tile unavailable — check internet access';
    const overlay = $('#mapOverlayStatus');
    if (overlay && geoMap.hasLayer(satelliteLayer)) {
      overlay.textContent = '● Satellite unavailable · OSM still available';
      overlay.className = 'map-overlay-status warn';
    }
  });
  satelliteLayer.on('load', () => {
    const status = $('#mapLayerStatus');
    if (status) status.textContent = 'Satellite imagery · Esri World Imagery';
  });

  setGeoBasemap('osm');

  geoMap.on('click', onGeoMapClick);

  $('#mapOsmBtn')?.addEventListener('click', () => setGeoBasemap('osm'));
  $('#mapSatelliteBtn')?.addEventListener('click', () => setGeoBasemap('satellite'));

  $('#mapSelectBtn')?.addEventListener('click', () => {
    selectingArea = !selectingArea;
    selectionCorner = null;
    $('#mapSelectBtn').textContent = selectingArea ? 'Click two corners' : 'Select area';
    $('#mapHelp').textContent = selectingArea
      ? 'Click the first corner, then the opposite corner. The second click automatically applies the geographic anchor.'
      : 'Click Select area, then click two opposite corners on the OpenStreetMap view.';
    geoMap.getContainer().style.cursor = selectingArea ? 'crosshair' : '';
  });

  $('#mapClearBtn')?.addEventListener('click', clearGeoSelection);
  $('#mapApplyBtn')?.addEventListener('click', applyGeoSelection);

  $('#mapHeading')?.addEventListener('input', () => {
    if (lastMapTelemetry) drawGeoOverlay(lastMapTelemetry);
  });

  $('#mapSearchBtn')?.addEventListener('click', searchGeoLocation);
  $('#mapSearch')?.addEventListener('keydown', e => {
    if (e.key === 'Enter') searchGeoLocation();
  });
}

function onGeoMapClick(e) {
  if (!selectingArea) return;

  if (!selectionCorner) {
    selectionCorner = e.latlng;
    if (selectionRect) geoMap.removeLayer(selectionRect);
    selectionRect = L.rectangle(
      [selectionCorner, selectionCorner],
      { color:'#1976d2', weight:2, fillOpacity:.12, pane:'geoSelection' }
    ).addTo(geoMap);
    $('#mapHelp').textContent = 'First corner set. Click the opposite corner to finish the selection.';
    return;
  }

  const a = selectionCorner, b = e.latlng;
  const south = Math.min(a.lat, b.lat), north = Math.max(a.lat, b.lat);
  const west = Math.min(a.lng, b.lng), east = Math.max(a.lng, b.lng);

  if ((north - south) < 0.0001 || (east - west) < 0.0001) {
    $('#mapHelp').textContent = 'Selection is too small. Click two corners farther apart.';
    return;
  }

  selectionRect.setBounds([[south, west], [north, east]]);
  selectingArea = false;
  selectionCorner = null;
  $('#mapSelectBtn').textContent = 'Select area';
  geoMap.getContainer().style.cursor = '';
  $('#mapApplyBtn').disabled = false;

  const bbox = {south, west, north, east};
  updateSelectionReadout(bbox);
  $('#mapHelp').textContent = 'Area selected. Applying the local-frame anchor and switching to satellite imagery…';

  // The operator should not need a second "Apply" click.
  applyGeoSelection();
}

function updateSelectionReadout(b) {
  const e = $('#mapSelectionReadout');
  if (e) e.textContent = `S ${b.south.toFixed(5)} · W ${b.west.toFixed(5)} · N ${b.north.toFixed(5)} · E ${b.east.toFixed(5)}`;
}

function clearGeoSelection() {
  if (selectionRect && geoMap) geoMap.removeLayer(selectionRect);
  selectionRect = null;
  selectionCorner = null;
  selectingArea = false;
  $('#mapApplyBtn').disabled = true;
  $('#mapSelectionReadout').textContent = 'No area selected';
  $('#mapSelectBtn').textContent = 'Select area';
  $('#mapHelp').textContent = 'Click Select area, then click two opposite corners on the OpenStreetMap view.';
  overlayLayers.forEach(x => geoMap && geoMap.removeLayer(x));
  overlayLayers = [];
  localVoOverlayLayers.forEach(x => localVoMap && localVoMap.removeLayer(x));
  localVoOverlayLayers = [];
  localVoLastBoundsKey = null;
  geoMap && (geoMap.getContainer().style.cursor = '');
  $('#mapOverlayStatus').textContent = '● Waiting for geographic anchor';
  $('#mapOverlayStatus').className = 'map-overlay-status';
  setGeoBasemap('osm');
}

async function applyGeoSelection() {
  if (!selectionRect) return;

  const b = selectionRect.getBounds();
  const heading = Math.max(-180, Math.min(180, Number($('#mapHeading').value || 0)));

  try {
    const result = await api('/api/map/select', {
      bbox: {
        south: b.getSouth(),
        west: b.getWest(),
        north: b.getNorth(),
        east: b.getEast()
      },
      heading_deg: heading
    });

    // Switch to satellite automatically after selecting the real-world area.
    setGeoBasemap('satellite');
    geoMap.fitBounds(
      [[b.getSouth(), b.getWest()], [b.getNorth(), b.getEast()]],
      { padding: [20, 20], maxZoom: 19 }
    );

    renderMap(result);
    drawLocalVoMap(result);

    $('#mapOverlayStatus').textContent =
      result.vo_trail?.length || result.trail?.length || result.pose_x != null
        ? '● VO / local trajectory overlay LIVE'
        : '● Geographic anchor applied · waiting for VO';
    $('#mapOverlayStatus').className = 'map-overlay-status ok';

    $('#mapHelp').textContent =
      'Satellite view active. Cyan = visual-odometry trajectory; green = rover pose; magenta = planned route.';
    toast('Area anchored — satellite + VO overlay active');
  } catch (e) {
    $('#mapOverlayStatus').textContent = '● Map anchor failed';
    $('#mapOverlayStatus').className = 'map-overlay-status warn';
    toast(`Map selection failed: ${e.message}`);
  }
}

async function searchGeoLocation() {
  const q = ($('#mapSearch').value || '').trim();
  if (!q || !geoMap) return;
  try {
    const r = await fetch(`https://nominatim.openstreetmap.org/search?format=jsonv2&limit=1&q=${encodeURIComponent(q)}`, {headers:{'Accept':'application/json'}});
    const rows = await r.json();
    if (!rows.length) { toast('Location not found'); return; }
    const lat = Number(rows[0].lat), lon = Number(rows[0].lon);
    geoMap.setView([lat, lon], Math.max(14, Number(rows[0].type === 'city' ? 12 : 15)));
    toast(`Centered on ${rows[0].display_name.split(',').slice(0,2).join(',')}`);
  } catch (e) { toast('OpenStreetMap search unavailable'); }
}

function localToLatLng(x, y, bbox, headingDeg) {
  const centerLat = (bbox.south + bbox.north) / 2;
  const centerLon = (bbox.west + bbox.east) / 2;
  const latRad = centerLat * Math.PI / 180;
  const mPerDegLat = 111320;
  const mPerDegLon = Math.max(1, 111320 * Math.cos(latRad));
  const theta = Number(headingDeg || 0) * Math.PI / 180;
  // Local +X is the east axis at 0°. Positive heading rotates +X toward north.
  const east = x * Math.cos(theta) - y * Math.sin(theta);
  const north = x * Math.sin(theta) + y * Math.cos(theta);
  return [centerLat + north / mPerDegLat, centerLon + east / mPerDegLon];
}

// Standalone monocular VO uses camera-forward as +Z.  On the geographic
// display, camera-forward must point toward the top of the map (north), so
// use an explicit forward-axis mapping here.  This keeps the VO START at the
// bottom and the current/head of the trajectory at the top.
function voToLatLng(x, z, bbox, headingDeg) {
  return localToLatLng(Number(x), Number(z), bbox, headingDeg);
}

function drawGeoOverlay(s) {
  initGeoMap();
  if (!geoMap) return;

  overlayLayers.forEach(x => geoMap.removeLayer(x));
  overlayLayers = [];

  const b = s.map_selection;
  if (!b) {
    $('#mapOverlayStatus').textContent = '● Select a geographic area';
    $('#mapOverlayStatus').className = 'map-overlay-status';
    return;
  }

  if (selectionRect) {
    selectionRect.setBounds([[b.south, b.west], [b.north, b.east]]);
  } else {
    selectionRect = L.rectangle(
      [[b.south, b.west], [b.north, b.east]],
      {color:'#1976d2', weight:2, fillOpacity:.03, pane:'geoSelection'}
    ).addTo(geoMap);
  }

  updateSelectionReadout(b);
  $('#mapHeading').value = Number(b.heading_deg || 0);

  // Actual standalone VO trajectory: x/z are the horizontal ground-plane axes.
  const voTrail = Array.isArray(s.vo_trail) ? s.vo_trail : [];
  if (voTrail.length > 1) {
    const pts = voTrail.map(p =>
      voToLatLng(Number(p[0]), -Number(p[2]), b, b.heading_deg)
    );
    overlayLayers.push(
      L.polyline(pts, {
        color:'#00e5ff',
        weight:5,
        opacity:.95,
        pane:'voTrajectory',
        lineJoin:'round',
        lineCap:'round'
      }).bindTooltip('VISUAL ODOMETRY TRAJECTORY')
    );
    const start = pts[0];
    overlayLayers.push(
      L.circleMarker(start, {
        radius:6, color:'#fff', fillColor:'#00e5ff',
        fillOpacity:1, weight:2, pane:'missionMarkers'
      }).bindTooltip('VO START')
    );
  }

  // LocalNav trajectory: this is the metric local pose used by the mission controller.
  const trail = Array.isArray(s.trail) ? s.trail : [];
  if (trail.length > 1) {
    const pts = trail.map(p =>
      localToLatLng(Number(p[0]), Number(p[1]), b, b.heading_deg)
    );
    overlayLayers.push(
      L.polyline(pts, {
        color:'#22c55e',
        weight:3,
        opacity:.75,
        dashArray:'4 5',
        pane:'missionOverlay',
        lineJoin:'round',
        lineCap:'round'
      }).bindTooltip('LOCAL NAV TRAJECTORY')
    );
  }

  // Planned A* route.
  const route = Array.isArray(s.route) ? s.route : [];
  if (route.length > 1) {
    const pts = route.map(p =>
      localToLatLng(Number(p[0]), Number(p[1]), b, b.heading_deg)
    );
    overlayLayers.push(
      L.polyline(pts, {
        color:'#ff2fb3',
        weight:4,
        dashArray:'9 7',
        opacity:.95,
        pane:'missionOverlay'
      }).bindTooltip('PLANNED A* ROUTE')
    );
    pts.forEach((p, i) => {
      overlayLayers.push(
        L.circleMarker(p, {
          radius:5, color:'#ff2fb3', fillColor:'#fff',
          fillOpacity:1, weight:2, pane:'missionMarkers'
        }).bindTooltip(`Waypoint ${i + 1}`)
      );
    });
  }

  // Live rover position from LocalNav.
  if (s.pose_x != null && Number.isFinite(Number(s.pose_x))) {
    const p = localToLatLng(
      Number(s.pose_x), Number(s.pose_y || 0), b, b.heading_deg
    );
    overlayLayers.push(
      L.circleMarker(p, {
        radius:9, color:'#fff', fillColor:'#22c55e',
        fillOpacity:1, weight:3, pane:'missionMarkers'
      }).bindTooltip('ROVER · live')
    );
  }

  // Confirmed survivors.
  (Array.isArray(s.survivors) ? s.survivors : []).forEach(sv => {
    const p = localToLatLng(
      Number(sv.x || 0), Number(sv.y || 0), b, b.heading_deg
    );
    overlayLayers.push(
      L.circleMarker(p, {
        radius:8, color:'#fff', fillColor:'#ef4444',
        fillOpacity:1, weight:2, pane:'missionMarkers'
      }).bindTooltip(`SURVIVOR S${sv.id}`)
    );
  });

  const hasOverlay = voTrail.length > 1 || trail.length > 1 || s.pose_x != null || route.length > 1;
  $('#mapOverlayStatus').textContent = hasOverlay
    ? `● OVERLAY LIVE · VO ${voTrail.length} poses · NAV ${trail.length} poses`
    : '● Geographic anchor applied · waiting for VO';
  $('#mapOverlayStatus').className = `map-overlay-status ${hasOverlay ? 'ok' : 'warn'}`;
}

function renderMap(s) {
  lastMapTelemetry = s;
  const hasNav = s.pose_x != null;
  setText('#mapVoStatus', hasNav ? (s.vo_ok ? '● TRACKING' : '● ESTIMATING') : '● DISABLED');
  setText('#mapPoseX', hasNav ? Number(s.pose_x).toFixed(2) : '—');
  setText('#mapPoseY', hasNav ? Number(s.pose_y).toFixed(2) : '—');
  setText('#mapYaw', hasNav ? Number(s.yaw_deg).toFixed(1) + '°' : '—');
  setText('#mapCoverage', hasNav ? Number(s.coverage_m2).toFixed(1) : '—');
  setText('#mapWaypoint', hasNav ? (s.waypoint || '0/0') : '—/—');

  const voTrailCount = Array.isArray(s.vo_trail) ? s.vo_trail.length : 0;
  const voState = s.vo_error ? `VO ERROR: ${s.vo_error}` :
    (s.vo_tracking ? `VO TRACKING · ${voTrailCount} poses · ${Number(s.vo_inliers || 0)} inliers` :
      (voTrailCount > 1 ? `VO ESTIMATING · ${voTrailCount} poses` : 'VO WAITING FOR MOTION'));
  const voStatusEl = $('#mapVoStatus');
  if (voStatusEl) {
    voStatusEl.textContent = '● ' + voState;
    voStatusEl.className = s.vo_error ? 'map-overlay-status warn' :
      (voTrailCount > 1 ? 'map-overlay-status ok' : 'map-overlay-status warn');
  }

  const segEl = $('#mapSegments');
  if (segEl) {
    const segs = Array.isArray(s.segments) ? s.segments : [];
    if (segs.length === 0) {
      segEl.innerHTML = '<p style="color:#888">No route loaded.</p>';
    } else {
      segEl.innerHTML = segs.map(sg => {
        const col = SEG_COLORS[sg.status] || '#888';
        const lbl = SEG_LABELS[sg.status] || sg.status;
        const from = Array.isArray(sg.from) ? sg.from.map(v => Number(v).toFixed(1)).join(',') : '?';
        const to = Array.isArray(sg.to) ? sg.to.map(v => Number(v).toFixed(1)).join(',') : '?';
        return `<div style="display:flex;align-items:center;gap:.75rem;padding:.45rem 0;border-bottom:1px solid #222;">` +
               `<span style="font-weight:700;min-width:2.5rem;">Seg ${sg.seg}</span>` +
               `<span style="color:#aaa;flex:1;font-size:.8rem;">(${from}) → (${to})</span>` +
               `<span style="color:#aaa;font-size:.8rem;">${Math.round((sg.covered || 0) * 100)}%</span>` +
               `<span style="font-weight:700;color:${col};min-width:4rem;text-align:right;font-size:.8rem;">${lbl}</span>` +
               `</div>`;
      }).join('');
    }
  }

  const surEl = $('#mapSurvivors');
  if (surEl) {
    const surs = Array.isArray(s.survivors) ? s.survivors : [];
    if (surs.length === 0) {
      surEl.innerHTML = '<p style="color:#888">None confirmed (need 3+ detections).</p>';
    } else {
      surEl.innerHTML = surs.map(sv => {
        const sx = Number(sv.x || 0).toFixed(2), sy = Number(sv.y || 0).toFixed(2);
        const conf = sv.conf ? Math.round(sv.conf * 100) + '%' : '--';
        return `<div style="display:flex;align-items:center;gap:.75rem;padding:.45rem 0;border-bottom:1px solid #222;">` +
               `<span style="font-weight:700;color:#e53935;min-width:2.5rem;">S${sv.id}</span>` +
               `<span style="color:#aaa;flex:1;font-size:.8rem;">(${sx}, ${sy}) m</span>` +
               `<span style="font-weight:700;color:#e53935;font-size:.8rem;">conf ${conf} · ${sv.hits} hits</span>` +
               `</div>`;
      }).join('');
    }
  }
  drawGeoOverlay(s);
  drawLocalVoMap(s);
}

async function poll() {
  try {
    const r = await fetch('/api/status', { cache: 'no-store' });
    if (r.ok) {
      const s = await r.json();
      render(s);
      renderMap(s);
    }
  } catch (e) {}
  setTimeout(poll, 500);
}

