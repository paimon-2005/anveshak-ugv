async function uploadVideo(file) {
  if (!file) return;
  const allowed = ['.mp4', '.avi', '.mov', '.mkv', '.webm', '.m4v'];
  const name = file.name.toLowerCase();
  if (!allowed.some(ext => name.endsWith(ext))) {
    toast('Choose a supported video file');
    return;
  }
  const button = $('#addVideo');
  button.disabled = true;
  button.textContent = 'Uploading…';
  try {
    const response = await fetch('/api/upload', {
      method: 'POST',
      headers: { 'Content-Type': 'application/octet-stream', 'X-Filename': file.name },
      body: file
    });
    const result = await response.json();
    if (!response.ok) throw Error(result.error || 'Video upload failed');
    toast('Test video loaded');
  } catch (e) {
    toast(e.message);
  } finally {
    button.disabled = false;
    button.textContent = '＋ Add Test Video';
    $('#videoInput').value = '';
  }
}

$('#addVideo').addEventListener('click', () => $('#videoInput').click());
$('#videoInput').addEventListener('change', e => uploadVideo(e.target.files[0]));
