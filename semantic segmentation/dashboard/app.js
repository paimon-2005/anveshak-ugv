let toastTimer;

function toast(message) {
  const el = $("#toast");
  if (!el) return;
  el.textContent = message;
  el.classList.add("show");
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => el.classList.remove("show"), 2600);
}

async function api(path, payload = {}) {
  const r = await fetch(path, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload)
  });
  const b = await r.json();
  if (!r.ok) throw Error(b.error || 'Request failed');
  return b;
}

function setPage(page) {
  $$('.nav-item').forEach(x => x.classList.toggle('active', x.dataset.page === page));
  $$('.page').forEach(x => x.classList.toggle('active', x.id === `page-${page}`));
  window.scrollTo({ top: 0, behavior: 'smooth' });
  if (page === 'map') {
    initGeoMap();
    initLocalVoMap();
    setTimeout(() => {
      geoMap && geoMap.invalidateSize(true);
      localVoMap && localVoMap.invalidateSize(true);
    }, 80);
    setTimeout(() => {
      geoMap && geoMap.invalidateSize(true);
      localVoMap && localVoMap.invalidateSize(true);
    }, 350);
  }
}
$$('.nav-item').forEach(b => b.addEventListener('click', () => setPage(b.dataset.page)));

function setText(id, value) {
  const e = $(id);
  if (e) e.textContent = value;
}

